package com.randspy.langocard

import org.json.JSONArray
import org.json.JSONObject
import org.junit.Assert.assertEquals
import org.junit.Test
import java.io.File

/**
 * Writes `content/typed-answer-fixtures.json` from [TypedAnswer], so the web's port in
 * `apps/backend/convex/typedAnswer.ts` can prove it checks answers identically. Fails when the
 * committed file is stale; delete it and run the test again to regenerate.
 */
class TypedAnswerFixturesTest {
    private val file = File("../../../content/typed-answer-fixtures.json")

    private class Case(val typed: String, val example: String, val noun: Boolean = false, val alternatives: Boolean = false)

    private val cases = listOf(
        Case("", "Voici {une intrigue}.", noun = true),
        Case("   ", "Voici {une intrigue}.", noun = true),
        Case("une intrigue", "Voici {une intrigue} ici.", noun = true),
        Case("  Une INTRIGUE ", "Voici {une intrigue} ici.", noun = true),
        Case("pourtant", "Il pleut, {Pourtant} elle sort."),
        Case("l'intrigue", "Voici {l’intrigue} ici.", noun = true),
        Case("un intrigue", "Voici {une intrigue} ici.", noun = true),
        Case("intrigue", "Voici {une intrigue} ici.", noun = true),
        Case("le arbre", "Voici {l'arbre} ici.", noun = true),
        Case("la porte", "Voici {une porte} ici.", noun = true),
        Case("un probleme", "Voici {un problème} ici.", noun = true),
        Case("un problême", "Voici {un problème} ici.", noun = true),
        Case("fiablé", "C'est {fiable} ici."),
        Case("mettre en oeuvre", "Il faut {mettre en œuvre} ce plan."),
        Case("se mefier", "Il faut {se méfier} ici."),
        Case("une intrige", "Voici {une intrigue} ici.", noun = true),
        Case("une affaire", "Voici {une intrigue} ici.", noun = true),
        Case("une", "Voici {une intrigue} ici.", noun = true),
        Case("méfier", "Il faut {se méfier} ici."),
        Case("rendu compte", "Il s'en est {rendu compte} trop tard."),
        Case("se rendre compte", "Il s'en est {rendu compte} trop tard."),
        Case("Parvenir", "Le train devrait {arriver|parvenir|atteindre la gare} ce soir.", alternatives = true),
        Case("arriver", "Le train devrait {arriver|parvenir|atteindre la gare} ce soir.", alternatives = true),
        Case("atteindre la gare", "Le train devrait {arriver|parvenir|atteindre la gare} ce soir.", alternatives = true),
        Case("parvenir", "Le train devrait {arriver|parvenir|atteindre la gare} ce soir."),
        Case("venir", "Le train devrait {arriver|parvenir|atteindre la gare} ce soir.", alternatives = true),
        Case("revé", "Il a {rêvé|songé} de toi.", alternatives = true),
        Case("songe", "Il a {rêvé|songé} de toi.", alternatives = true),
        Case("probleme", "Voici {problème} ici.", noun = true),
        Case("la pourtant", "{pourtant}", noun = true),
        Case("idée", "Une {idée} ici.", noun = true),
        Case("une  intrigue", "Voici {une intrigue} ici.", noun = true),
        Case("uneintrigue", "Voici {une intrigue} ici.", noun = true),
        Case("L’ARBRE", "Voici {l'arbre} ici.", noun = true),
        Case("des idees", "Elle a {des idées}.", noun = true),
    )

    private fun parts(parts: List<AnswerPart>) = JSONArray(parts.map { JSONObject().put("text", it.text).put("marked", it.marked) })

    private fun generate(): JSONObject = JSONObject()
        .put("note", "Generated by TypedAnswerFixturesTest from Android's TypedAnswer; do not edit.")
        .put("cases", JSONArray(cases.map { case ->
            val answer = TypedAnswer.of(case.typed, Example(case.example), case.noun, case.alternatives)
            JSONObject().put("typed", case.typed).put("example", case.example).put("noun", case.noun)
                .put("alternatives", case.alternatives).put("expected", if (answer == null) JSONObject.NULL else JSONObject()
                    .put("match", answer.match.name).put("suggested", answer.match.suggested.name)
                    .put("target", answer.target).put("expected", answer.expected)
                    .put("typedParts", parts(answer.typedParts)).put("expectedParts", parts(answer.expectedParts)))
        }))

    @Test fun `fixtures match TypedAnswer`() {
        val text = generate().toString(1) + "\n"
        if (!file.exists()) file.writeText(text)
        assertEquals(generate().toString(), JSONObject(file.readText()).toString())
    }
}
